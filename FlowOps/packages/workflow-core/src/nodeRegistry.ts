/**
 * Node Registry Query & Validation Helpers
 */
export function getNodeDefinition(type: string): FlowOpsNodeDefinition | undefined {
  return FLOWOPS_NODE_REGISTRY.find(n => n.type === type);
}

export function getAllNodeDefinitions(): FlowOpsNodeDefinition[] {
  return FLOWOPS_NODE_REGISTRY;
}

export function getNodesByCategory(category: NodeCategory): FlowOpsNodeDefinition[] {
  return FLOWOPS_NODE_REGISTRY.filter(n => n.category === category);
}

export function isNodeExecutable(type: string): boolean {
  const node = getNodeDefinition(type);
  if (!node) return false;
  return node.availability === 'AVAILABLE' || node.availability === 'BETA';
}

export function validateNodeAvailability(type: string): { valid: boolean; error?: string } {
  const node = getNodeDefinition(type);
  if (!node) {
    // If it's a legacy or custom node type not yet registered, allow if recognized
    return { valid: true };
  }
  if (node.availability === 'PLANNED') {
    return {
      valid: false,
      error: `Node "${node.displayName}" (${node.type}) is currently PLANNED and cannot be published to execution.`,
    };
  }
  if (node.availability === 'DISABLED') {
    return {
      valid: false,
      error: `Node "${node.displayName}" (${node.type}) is DISABLED by security policy.`,
    };
  }
  return { valid: true };
}
