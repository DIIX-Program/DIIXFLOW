// 3. TYPED PORT SYSTEM
// ============================================================================

export type PortDataType = 'IMAGE' | 'PROMPT' | 'MEDIA_RESULT' | 'ANY';

export interface PortDefinition {
  id: string;
  name: string;
  dataType: PortDataType;
  required?: boolean;
  maxConnections?: number;
}

export function canConnectPorts(sourceType: PortDataType, targetType: PortDataType): boolean {
  if (sourceType === 'ANY' || targetType === 'ANY') return true;
  if (sourceType === targetType) return true;
  // A MediaResult (e.g. image generated by Muse) can connect to an IMAGE input port for chaining
  if (sourceType === 'MEDIA_RESULT' && targetType === 'IMAGE') return true;
  return false;
}

